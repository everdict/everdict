#!/usr/bin/env node
// ── A GUARD ONE DOOR CARRIES AND ITS SIBLING DOES NOT — CHECKED (arch-review 119) ───────────────────
//
// This review series keeps finding one shape, and found it three separate times in a single wave:
//
//   · `PUT /agents/:id` gained a `teamOfEntity` gate; `PUT /models/:id`, the same act on the same kind of
//     asset, kept a bare `models:write` — a member of another team minted a Team-A-owned version.
//   · `create_judge` / `register_harness` file a new capability under a team; `create_rubric`,
//     `create_model`, `create_runtime` and `create_agent` wrote with none — the asset was born unowned,
//     which is writable by everyone.
//   · `get_dataset` refuses a private team's dataset; `diff_datasets` returned BOTH versions of it.
//
// Every one is the same sentence: a resource decided what its doors owe, and one door did not hear. Reading
// for it works exactly once — the door written after the lesson is the door that never learned. So the rule
// is mechanical: WITHIN ONE RESOURCE, a door that names an entity carries the guards its siblings carry.
//
// This is a RATCHET over a baseline, not a sweep. What is recorded today is history; what may not happen is
// a new door joining a resource without the guard its neighbours already have, or an existing door losing
// one. The count only goes down.
//
// Reads SOURCE only (no build, no deps), prints every violation, exits 1.
//   --write   regenerate the baseline (the only way a list this size stays honest)
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const API = path.join(root, "apps", "api", "src", "api");
const BASELINE = path.join(root, "scripts", "guard-siblings-baseline.txt");
const HEADER = `# Generated by scripts/check-guard-siblings.mjs --write. One line per door that names an entity and
# does NOT carry a guard its siblings in the same resource do: <resource>\t<transport>\t<door>\t<missing,…>
# Every line is a door somebody has to look at. New lines are refused; removed ones must be regenerated here
# in the same change, so the number never drifts from what the tree carries.
`;

// The two questions a door on a team-owned resource has to answer, and the vocabulary each is asked in.
// `plain(...)` is the creator-or-admin lane (delete cores authorize inside), and a service that gates
// internally (`setVersionTags`, `deleteXVersion`, `moveCapabilityToTeam`) counts as carrying the guard.
const GUARDS = {
  // ⚠️ A CALL, never a mention. The first draft matched the bare names and stayed GREEN over its own target:
  // neutralizing `PUT /models/:id` left `let owner: Awaited<ReturnType<typeof teamOfEntity>>;` behind, and a
  // TYPE reference kept the door looking guarded. A guard nobody saw fail is a comment (rule `testing`), and
  // this repository has shipped two scanner drafts green over the defect they were written for.
  visibility: [
    /(assertEntityVisible|assertTeamVisible|keepVisible|visibleTeamsFor|ownedByVisibleTeam|scorecardOwner|assertBatchReachable|canSeeTeam)\s*\(/,
  ],
  // A door may carry the answer itself (`teamOfEntity(...)`, `runForTeam(...)`) or delegate to a core that
  // authorizes inside — the delete cores are creator-or-admin, which is STRICTER than the team rule, and the
  // version-tag and move cores resolve the owner themselves. Both count: the rule asks that the door not
  // decide without asking, not that it ask in one particular place.
  ownership: [
    /(teamOfEntity|teamOfVersion|runForTeam|teamForNew|setVersionTags|moveCapabilityToTeam|scorecardOwner|assertBatchReachable|plain|delete[A-Z]\w*Versions?|creatorOf)\s*\(/,
    // …or the scope handed DIRECTLY: `gate(principal, "x:write", owner)` / `authorize(principal, "x", scope)`
    // / `run(principal, "x", fn, owner)`. A door that resolved the owner itself is guarded just as much as one
    // that called a helper, and counting only helpers would flag `POST /campaigns/:id/settle`, which does it
    // inline.
    /\b(gate|authorize)\(\s*principal\s*,\s*"[a-z:_]+"\s*,/,
    /\brun\(\s*\n?\s*principal\s*,[\s\S]{0,400}?,\s*owner\s*,?\s*\)/,
    // …or the door HANDED the principal to a core that decides — `attestDatasetConstitution(deps, principal,
    // …)` is admin-gated inside the action so both transports inherit one rule, and `scorecards.delete({
    // principal, id })` is creator-or-admin in the service, which the route's own comment states. Delegation
    // is asking; what the rule refuses is deciding WITHOUT asking.
    /\battestDatasetConstitution\s*\(|\.\w+\(\s*\{\s*principal\b/,
  ],
};

// Resources whose access model is deliberately NOT the team ceiling. Each entry says which model it uses
// instead; an entry whose resource has since adopted the ceiling is stale and fails.
const OTHER_MODEL = new Map([
  ["capability", "its own `visibility` field (setVisibility / mayPublishPublic / defaultVisibilityFor)"],
  ["issue", "the tracker's records are filing + visibility only — docs/tracker.md says so by name"],
  ["project", "same as issue — not roster-gated on write"],
  ["initiative", "same as issue — not roster-gated on write"],
  ["cycle", "belongs to a team by construction; its routes resolve the team from the cycle"],
  ["api-key", "self-scoped: each user issues and revokes only their OWN subject's keys"],
  ["browser-session", "personal / self-scoped (owner = subject, like connected accounts)"],
  [
    "browser-profile",
    "dual-scoped private|workspace, gated per visibility INSIDE the service (private = creator-only 404, workspace = creator-or-admin 403)",
  ],
  ["comment", "author-or-admin on delete; a comment belongs to the resource it is on, not to a team"],
  ["runner", "a paired DEVICE, workspace-scoped — it carries no teamId at all"],
]);

// ── AN ADMIN-ONLY ACTION IS ITS OWN, STRONGER RULE ─────────────────────────────────────────────────
//
// `docs/auth.md`: "An ADMIN reaches every team (one they are not on would otherwise be un-administrable)."
// So a door gated on an admin-only action does not owe a team scope — the role already answers a strictly
// harder question. `POST /runtimes/:id/versions/:version/control` is the case that taught this: its
// vocabulary is `stopWorkload` / `reclaimIdle` / `cordonNode`, it looked like the wave's other findings, and
// it is not one.
//
// READ from the matrix, never copied: a second spelling of who-may-do-what diverges the first time somebody
// edits one of them (rule `protocol` L3). The parse is deliberately narrow — the admin arm of
// `ROLE_PERMISSIONS` minus everything viewer/member also hold — and it FAILS LOUDLY if the file's shape
// changes, because a silently empty set would quietly widen this whole check.
function adminOnlyActions() {
  const file = path.join(root, "packages", "domain", "src", "auth", "authz.ts");
  const src = readFileSync(file, "utf8");
  const arm = (role) => {
    const m = src.match(new RegExp(String.raw`\n  ${role}: new Set<Action>\(\[([\s\S]*?)\n  \]\)`));
    if (!m)
      throw new Error(
        `check-guard-siblings: cannot read the ${role} arm of ROLE_PERMISSIONS — the role matrix moved, and guessing would widen this check`,
      );
    return new Set([...m[1].matchAll(/"([a-z_]+:[a-z_]+)"/g)].map((x) => x[1]));
  };
  const admin = arm("admin");
  for (const lower of [arm("viewer"), arm("member")]) for (const a of lower) admin.delete(a);
  if (admin.size === 0)
    throw new Error(
      "check-guard-siblings: the admin-only set came out empty — refusing to run over a matrix I cannot read",
    );
  return admin;
}
const ADMIN_ONLY = adminOnlyActions();

// The actions a door gates on, in either transport's spelling.
const actionsOf = (body) =>
  [...body.matchAll(/(?:gate|authorize|run|runForTeam)\(\s*\n?\s*(?:principal|ctx)\s*,\s*"([a-z_]+:[a-z_]+)"/g)].map(
    (m) => m[1],
  );

const files = [];
(function walk(dir) {
  for (const entry of readdirSync(dir)) {
    const full = path.join(dir, entry);
    if (statSync(full).isDirectory()) walk(full);
    else if (full.endsWith(".routes.ts") || full.endsWith(".mcp.ts")) files.push(full);
  }
})(API);

// One door = one route handler or one MCP tool, with the source window that belongs to it.
function doorsOf(file) {
  const src = readFileSync(file, "utf8");
  const out = [];
  if (file.endsWith(".routes.ts")) {
    const hits = [...src.matchAll(/app\.(get|post|put|patch|delete)</g)];
    for (const [i, hit] of hits.entries()) {
      const body = src.slice(hit.index, i + 1 < hits.length ? hits[i + 1].index : src.length);
      const route = (body.match(/"(\/[^"]*)"/) ?? [])[1] ?? "?";
      out.push({
        transport: "HTTP",
        name: `${hit[1].toUpperCase()} ${route}`,
        body,
        // Names ONE entity: a path parameter, not a collection.
        namesEntity: /:id\b/.test(route),
        write: hit[1] !== "get",
      });
    }
  } else {
    const hits = [...src.matchAll(/server\.registerTool\(\s*\n?\s*"([a-z0-9_]+)"/g)];
    for (const [i, hit] of hits.entries()) {
      const body = src.slice(hit.index, i + 1 < hits.length ? hits[i + 1].index : src.length);
      const schema = (body.match(/inputSchema:\s*\{[\s\S]{0,400}?\n\s{6}\}/) ?? [""])[0];
      out.push({
        transport: "MCP",
        name: hit[1],
        body,
        namesEntity: /\bid\s*:/.test(schema),
        write: !/readOnlyHint:\s*true/.test(body),
      });
    }
  }
  return out;
}

const byResource = new Map();
for (const file of files) {
  const resource = path
    .relative(API, file)
    .split(path.sep)[0]
    .replace(/\.(routes|mcp)\.ts$/, "");
  if (!byResource.has(resource)) byResource.set(resource, []);
  for (const door of doorsOf(file)) byResource.get(resource).push(door);
}

const observed = [];
for (const [resource, doors] of byResource) {
  if (OTHER_MODEL.has(resource)) continue;
  const entityDoors = doors.filter((d) => d.namesEntity);
  if (entityDoors.length < 2) continue; // nothing to be a sibling of
  for (const kind of ["visibility", "ownership"]) {
    // What this resource has DECIDED it owes: whether any of its entity doors carries this guard at all.
    const reads = entityDoors.filter((d) => (kind === "visibility" ? !d.write : d.write));
    if (reads.length < 2) continue;
    const carries = (d) => GUARDS[kind].some((re) => re.test(d.body));
    const carrying = reads.filter(carries);
    if (carrying.length === 0) continue; // this resource does not use this guard — not a deviation
    for (const door of reads) {
      // An admin-only action already governs every team; asking for a scope on top would be asking for less.
      const gated = actionsOf(door.body);
      if (gated.length > 0 && gated.every((a) => ADMIN_ONLY.has(a))) continue;
      if (!carries(door)) observed.push(`${resource}\t${door.transport}\t${door.name}\t${kind}`);
    }
  }
}
observed.sort();

if (process.argv.includes("--write")) {
  writeFileSync(BASELINE, `${HEADER}${observed.join("\n")}\n`);
  console.log(`wrote ${observed.length} entries to ${path.relative(root, BASELINE)}`);
  process.exit(0);
}

const baseline = existsSync(BASELINE)
  ? readFileSync(BASELINE, "utf8")
      .split("\n")
      .map((l) => l.replace(/\r$/, ""))
      .filter((l) => l !== "" && !l.startsWith("#"))
  : [];

const problems = [];
const recorded = new Set(baseline);
const seen = new Set(observed);
for (const row of observed)
  if (!recorded.has(row)) {
    const [resource, transport, door, kind] = row.split("\t");
    problems.push(`${resource} ${transport} ${door} carries no ${kind} guard, and its siblings in ${resource} do`);
  }
for (const row of baseline)
  if (!seen.has(row))
    problems.push(`baseline names "${row.replace(/\t/g, " ")}", which no longer deviates — regenerate`);
for (const resource of OTHER_MODEL.keys())
  if (!byResource.has(resource)) problems.push(`OTHER_MODEL names ${resource}, which is not a resource here`);

if (problems.length > 0) {
  console.error(`✖ guard siblings — ${problems.length} problem(s):\n`);
  for (const p of problems.slice(0, 40)) console.error(`  ✗ ${p}`);
  if (problems.length > 40) console.error(`  … and ${problems.length - 40} more`);
  console.error(
    `\n  A guard one door carries and its sibling does not is how every one of arch-review 119's findings
  reached production. Add the guard, or — if this door genuinely answers a different question — say so in
  OTHER_MODEL with the model it uses instead, and regenerate:
      node ${path.relative(root, fileURLToPath(import.meta.url))} --write`,
  );
  process.exit(1);
}

console.log(
  `PASS guard siblings: ${[...byResource.keys()].length} resources, ${observed.length} recorded deviation(s), none new. ${OTHER_MODEL.size} resource(s) declare a different access model.`,
);
